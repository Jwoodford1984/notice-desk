// Generates supabase/seed.sql from the prototype's sample data, so the demo
// workspace in Supabase matches what the clickable prototype shows.
// Usage: node scripts/build-seed.mjs <path to prototype index.html>
import fs from 'node:fs';
import vm from 'node:vm';
import { BPIPE_USAGE, BPIPE_APPS } from './bpipe-sample.mjs';

const html = fs.readFileSync(process.argv[2], 'utf8');
const start = html.indexOf('/* ---------------- Sample reference data');
const end = html.indexOf('/* ---------------- State');
const code = html.slice(start, end) +
  '\n;globalThis.out = {SAMPLE_USERS, SERVICE_DESC, SAMPLE_NOTICES, usage: buildSampleUsage(), perms: buildSamplePerms()};';
const ctx = {}; vm.createContext(ctx); vm.runInContext(code, ctx);
const { SAMPLE_NOTICES, usage, perms } = ctx.out;

const q = v => (v === null || v === undefined || v === '') ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const arr = a => `array[${a.map(q).join(',')}]::text[]`;
const T = '00000000-0000-4000-8000-000000000001';
const SRC = { usage: '00000000-0000-4000-8000-0000000000a1', perms: '00000000-0000-4000-8000-0000000000a2', bpipe: '00000000-0000-4000-8000-0000000000a3' };
const nid = i => `00000000-0000-4000-8000-0000000001${String(i).padStart(2, '0')}`;
const fid = i => `00000000-0000-4000-8000-0000000002${String(i).padStart(2, '0')}`;
const STATUS = { 'New': 'new', 'Awaiting file': 'awaiting_file', 'Matched': 'matched', 'In review': 'in_review', 'Actioned': 'actioned', 'Not relevant': 'not_relevant' };
const KIND = { RIC: 'ric', Ticker: 'ticker', Exchange: 'exchange' };

const out = [];
out.push('-- Demo workspace generated by scripts/build-seed.mjs. Invented people and emails.');
out.push('begin;');
out.push(`insert into public.tenants(id, name, slug) values ('${T}', 'Northgate Bank (demo)', 'northgate-demo') on conflict do nothing;`);

out.push(`insert into public.data_sources(id, tenant_id, kind, file_name, report_version, generated_label, period_label, row_count, is_current) values
 ('${SRC.usage}', '${T}', 'lseg_usage', 'Sample usage (pseudonymised from small_fake_usage_LSEG_Q2.csv)', 'dacs7.11.0.F1', '03/03/2025 15:02', '01 Feb 2025 – 28 Feb 2025', ${usage.length}, true),
 ('${SRC.perms}', '${T}', 'lseg_permissions', 'Sample permissions (pseudonymised from Latest Permission file 040326.csv)', 'dacs8.1.0.F1', '03/03/2026 09:40', null, ${perms.length}, true),
 ('${SRC.bpipe}', '${T}', 'bpipe_usage', 'Sample B-PIPE usage', null, '01/11/2026', 'Oct 2026', ${BPIPE_USAGE.length}, true);`);

out.push('insert into public.usage_items(tenant_id, source_id, vendor, login, user_name, user_group, cost_centre, email, service_code, service_desc, item) values');
const urows = usage.map(u => `('${T}','${SRC.usage}','LSEG',${q(u.login)},${q(u.uname)},${q(u.ugroup)},${q(u.costctr)},null,${q(u.global)},${q(u.desc)},${q(u.item)})`);
const brows = BPIPE_USAGE.map(b => `('${T}','${SRC.bpipe}','Bloomberg',${q(b[0])},${q(b[1])},null,${q(b[2])},${q(b[3])},${q(b[5])},null,${q(b[4])})`);
out.push(urows.concat(brows).join(',\n') + ';');

out.push('insert into public.permissions(tenant_id, source_id, login, user_name, email, service_code, service_desc, fee_structure, activated_label) values');
out.push(perms.map(p => `('${T}','${SRC.perms}',${q(p.login)},${q(p.uname)},${q(p.email)},${q(p.global)},${q(p.desc)},${q(p.fee)},${q(p.activation)})`).join(',\n') + ';');

const apps = {
  murex4_prd: ['Murex (production)', 'Front Office Systems – Murex team', 'murex-support@northgate-demo.example'],
  murex4_uat: ['Murex (UAT)', 'Front Office Systems – Murex team', 'murex-support@northgate-demo.example'],
  rtds_dss_streaming_qfeq_prd: ['DSS via RTDS (production)', 'Quant Platform', 'quant-platform@northgate-demo.example'],
  courbes: ['Interest rate curves engine', 'Market Risk IT', 'risk-it@northgate-demo.example'],
  ...Object.fromEntries(Object.entries(BPIPE_APPS).map(([k, v]) => [k, [v.name, v.owner, v.email]])),
};
out.push('insert into public.applications(tenant_id, login, name, owner_team, owner_email) values');
out.push(Object.entries(apps).map(([l, [n, o, e]]) => `('${T}',${q(l)},${q(n)},${q(o)},${q(e)})`).join(',\n') + ';');

// Notices: insert as new/awaiting, attach files (trigger moves them to matched), then set final status
SAMPLE_NOTICES.forEach((n, i) => {
  const vendor = n.kind === 'Ticker' ? 'Bloomberg' : 'LSEG';
  out.push(`insert into public.notices(id, tenant_id, ref, vendor, source, title, change_type, kind, effective_date, received_date, service_codes, requires_file, status, portal_url, summary) values
 ('${nid(i)}','${T}',${q(n.id)},${q(n.vendor)},${q(n.source)},${q(n.title)},${q(n.type)},'${KIND[n.kind]}','${n.effective}','${n.received}',${arr(n.globals)},${n.requiresFile},'${n.requiresFile ? 'awaiting_file' : 'new'}',${q(n.portal)},${q(n.summary)});`);
  const f = n.file || (n.id === 'BBG-26-118' ? n.sampleFile : null); // demo: Bloomberg file attached so ticker matching shows
  if (f) {
    out.push(`insert into public.notice_files(id, tenant_id, notice_id, file_name, sheet_name, detected_columns, row_count) values
 ('${fid(i)}','${T}','${nid(i)}',${q(f.name)},'Affected Instruments',${q(JSON.stringify({ instrument: f.header[0], new_code: f.header[1], change: f.header[2], effective: f.header[3] }))}::jsonb,${f.rows.length});`);
    out.push('insert into public.notice_instruments(tenant_id, notice_id, file_id, vendor, current_code, new_code, change_type, effective_label) values');
    out.push(f.rows.map(r => `('${T}','${nid(i)}','${fid(i)}','${vendor}',${q(r.old)},${q(r.new)},${q(r.change)},${q(r.eff)})`).join(',\n') + ';');
  }
});
// Actions for the two notices that have them in the prototype
const n1 = SAMPLE_NOTICES.findIndex(n => n.id === 'DN-26-1142');
const n7 = SAMPLE_NOTICES.findIndex(n => n.id === 'DN-26-1129');
out.push(`select public.create_actions_for_notice('${nid(n1)}');`);
out.push(`select public.create_actions_for_notice('${nid(n7)}');`);
out.push(`update public.actions set status = 'done' where notice_id = '${nid(n7)}';`);
out.push(`update public.actions set status = 'done' where id = (select id from public.actions where notice_id = '${nid(n1)}' order by number limit 1);`);
out.push(`update public.actions set status = 'in_progress' where id = (select id from public.actions where notice_id = '${nid(n1)}' order by number offset 1 limit 1);`);
out.push('commit;');
fs.writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n') + '\n');
console.log(`seed.sql: ${usage.length + BPIPE_USAGE.length} usage rows, ${perms.length} permission rows, ${SAMPLE_NOTICES.length} notices`);
